#!/usr/bin/env python3
"""Generate the `klt sim` requests that rerun RECORD-004's crowbar grid (#331).

    PDK_ROOT=<parent of ihp-sg13cmos5l> python3 -I gen_rerun331_requests.py OUTDIR

`run_schmitt_crowbar.sh` (the RECORD-004 entry point) loops local `ngspice -b`
over 4 variants x 5 MOS corners x 3 temperatures x 3 supplies = 180 points;
the host rule forbids that.  This generator expresses the SAME grid as four
`klt sim` requests (one per variant: corners.process x temperature_c x
supply_v = 45 units each) on the DUT frozen at `36e4bae`
(`../netlist-snapshots/lock_detector_hystfix.spice`), with the same
`l=0.5u` -> `l=2u/4u/8u` substitution the script performs.

Disclosed differences from the script's deck, all forced by the request model
(a request cannot substitute @VSUP@/@VMID@ or read a wrdata trace):
  * the input ramp is a B-source scaled by v(vdd) (0 -> vdd in 2 us, back in
    2 us) and the mid-rail threshold is a B-source node v(vmid)=v(vdd)/2, so
    `corners.supply_v` (an `alter` of Vdd) moves both with the supply;
  * the DUT cell is inlined into each netlist (no .include);
  * measurements are .meas cards: vth_up, vth_dn, hysteresis, peak current in
    each ramp direction (+ the time of the peak, from which the input voltage
    at the peak is vsup*t/2us on the rise), the current with the input at
    mid-rail (`i_vdd2_*`), and the rail currents.  `i_vdd2_*` is NOT the
    script's `i_midband_*` (that is taken at the midpoint of the two measured
    trip points, which a deck-level .meas cannot reference); the two are
    different quantities and are not compared as if equal.  `v_at_i_peak_*`
    and `i_worst` are derived by the post-processor, not measured.
"""
import json, os, pathlib, re, sys

here = pathlib.Path(__file__).resolve().parent
snap = here.parent / "netlist-snapshots" / "lock_detector_hystfix.spice"
out = pathlib.Path(sys.argv[1]).resolve()
pdk_root = os.environ.get("PDK_ROOT", "/home/ubuntu/share/pdk")
pdk = os.environ.get("PDK", "ihp-sg13cmos5l")
tech = f"{pdk_root}/{pdk}/libs.tech/ngspice"

text = snap.read_text()
m = re.search(r"(?ms)^\.subckt\s+schmitt_hv\b.*?^\.ends\s*$", text)
assert m, "schmitt_hv subckt not found in the frozen snapshot"
cell = m.group(0)
assert cell.count("l=0.5u") == 6

TB = """* generated by gen_rerun331_requests.py (variant {variant}) -- do not edit
.global sub!
{cell}

Vsub sub! 0 0
Vdd vdd 0 dc 3.3
Bmid vmid 0 v=v(vdd)/2
Bin vin 0 v='v(vdd)*(time<2u ? time/2u : (time<4u ? (4u-time)/2u : 0))'
Xsch vin sout vdd 0 schmitt_hv
.options reltol=1e-3 abstol=1e-10 vntol=1e-5 chgtol=1e-13
"""
MEAS = [
  ("vth_up", "V", ".meas tran vth_up find v(vin) when v(sout)=v(vmid) fall=1"),
  ("vth_dn", "V", ".meas tran vth_dn find v(vin) when v(sout)=v(vmid) rise=1"),
  ("hysteresis", "V", ".meas tran hysteresis param='vth_up-vth_dn'"),
  ("i_peak_rise", "A", ".meas tran i_peak_rise max par('abs(i(Vdd))') from=0 to=2u"),
  ("t_peak_rise", "s", ".meas tran t_peak_rise max_at par('abs(i(Vdd))') from=0 to=2u"),
  ("i_peak_fall", "A", ".meas tran i_peak_fall max par('abs(i(Vdd))') from=2u to=4u"),
  ("t_peak_fall", "s", ".meas tran t_peak_fall max_at par('abs(i(Vdd))') from=2u to=4u"),
  ("i_vdd2_rise", "A", ".meas tran i_vdd2_rise find par('abs(i(Vdd))') when v(vin)=v(vmid) rise=1"),
  ("i_vdd2_fall", "A", ".meas tran i_vdd2_fall find par('abs(i(Vdd))') when v(vin)=v(vmid) fall=1"),
  ("i_rail_lo", "A", ".meas tran i_rail_lo find par('abs(i(Vdd))') at=0"),
  ("i_rail_hi", "A", ".meas tran i_rail_hi find par('abs(i(Vdd))') at=2u"),
]
for variant, l in (("asdrawn", "0.5u"), ("long2u", "2u"),
                   ("long4u", "4u"), ("long8u", "8u")):
    d = out / variant
    d.mkdir(parents=True, exist_ok=True)
    body = TB.format(variant=variant, cell=cell.replace("l=0.5u", "l=" + l))
    (d / "crowbar.cir").write_text(body)
    req = {
        "engine": "ngspice", "netlist": "crowbar.cir",
        "models": {"lib": f"{tech}/models/cornerMOShv.lib"},
        "analysis": {"kind": "tran", "args": "1n 4u"},
        "measurements": [{"name": n, "unit": u, "spice": s} for n, u, s in MEAS],
        "options": {
            "osdi_preload": [f"{tech}/osdi/{n}.osdi"
                             for n in ("psp103", "psp103_nqs", "mosvar")],
            "stage_model_inputs": True, "timeout_s": 1800},
        "backend": "batch",
        "corners": {"process": ["mos_tt", "mos_ss", "mos_ff", "mos_sf", "mos_fs"],
                    "supply_v": {"vdd": [2.97, 3.3, 3.63]},
                    "temperature_c": [-40, 27, 125]},
        "batch": {"capacity_wait_s": 600},
    }
    (d / "request.json").write_text(json.dumps(req, indent=2) + "\n")
    print("wrote", d / "request.json")
