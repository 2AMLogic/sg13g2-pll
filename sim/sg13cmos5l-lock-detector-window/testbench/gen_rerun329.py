#!/usr/bin/env python3
"""Generate the klt-sim inputs for the issue #329 rerun of RECORD-003.

Reconstructs the DUT at producing commit a595772 (NOT today's design) for both
PDK arms, builds the as-drawn control exactly as run_schmitt_rewire.sh's
as_drawn() does, and writes one decks+request per (pdk, dut, supply).  Corner
axes (mos x temp) go in the request; the supply is a literal per request
because the original deck's `meas ... when v(sout)=VMID` cannot follow
corners.supply_v.  No simulation is run here.
"""
import json, subprocess, sys, pathlib

REC = pathlib.Path(__file__).resolve().parent.parent
REPO = REC.parent.parent
ARMS = {"cmos5l": ("ihp-sg13cmos5l", "design/sg13cmos5l/netlist/lock_detector.spice"),
        "g2": ("ihp-sg13g2", "design/netlist/lock_detector.spice")}
SUBS = [("XMP3 VSS OUT np VDD sg13_hv_pmos", "XMP3 np OUT VDD VDD sg13_hv_pmos"),
        ("XMN3 VDD OUT nn VSS sg13_hv_nmos", "XMN3 nn OUT VSS VSS sg13_hv_nmos")]
SUPPLIES = ["2.97", "3.3", "3.63"]
TMPL = (REC / "testbench/tb_schmitt_rewire.sp.tmpl").read_text()

def deck(dut_file, vsup):
    vmid = "%.6f" % (float(vsup) / 2)
    body = TMPL.split(".lib @PDK_ROOT@", 1)[1].split("\n", 1)[1]  # drop .lib line
    body = body.replace(".option scale=1 temp=@TEMP@\n", ".option scale=1\n")
    body = body.replace(".include @DUT@", '.include "../../netlist-snapshots/rerun329/%s"' % dut_file)
    body = body.replace("@VSUP@", vsup).replace("@VMID@", vmid)
    body = body.split(".tran 1n 4u")[0] + ".end\n"  # analysis + measurements live in the request
    return "* issue #329 rerun deck generated by gen_rerun329.py from tb_schmitt_rewire.sp.tmpl\n" + body

def request(pdk, netlist, vsup, probe):
    r = "$PDK_ROOT/" + pdk + "/libs.tech/ngspice/osdi/"
    vmid = "%.6f" % (float(vsup) / 2)
    return {
        "engine": "ngspice", "backend": "batch", "netlist": netlist,
        "models": {"pdk": pdk, "lib": "libs.tech/ngspice/models/cornerMOShv.lib"},
        "corners": {"process": ["mos_tt"] if probe else ["mos_tt", "mos_ff", "mos_ss"],
                    "temperature_c": [27] if probe else [-40, 27, 125]},
        "analysis": {"kind": "tran", "args": "1n 4u"},
        "measurements": [
            {"name": "vth_up", "spice": ".meas tran vth_up find v(vin) when v(sout)=%s fall=1" % vmid},
            {"name": "vth_dn", "spice": ".meas tran vth_dn find v(vin) when v(sout)=%s rise=1" % vmid}],
        "options": {"osdi_preload": [r + o for o in ("psp103.osdi", "psp103_nqs.osdi", "mosvar.osdi", "r3_cmc.osdi")],
                    "timeout_s": 900, "keep_artifacts": True},
    }

def main():
    for arm, (pdk, rel) in ARMS.items():
        fixed = subprocess.check_output(["git", "-C", str(REPO), "show", "a595772:" + rel], text=True)
        asdrawn = fixed
        for new, old in SUBS:
            if new not in asdrawn:
                sys.exit("a595772:%s lacks fixed connection %r" % (rel, new))
            asdrawn = asdrawn.replace(new, old)
        for dut, text in (("as_drawn", asdrawn), ("rewired", fixed)):
            (REC / "netlist-snapshots/rerun329" / ("%s_%s.spice" % (arm, dut))).write_text(text)
            for v in SUPPLIES:
                tag = "%s_%s_%s" % (arm, dut, v.replace(".", "p"))
                (REC / "testbench/rerun329" / ("tb_%s.sp" % tag)).write_text(deck("%s_%s.spice" % (arm, dut), v))
                req = request(pdk, "../testbench/rerun329/tb_%s.sp" % tag, v, False)
                (REC / "requests" / ("schmitt_rewire_%s.request.json" % tag)).write_text(json.dumps(req, indent=2) + "\n")
    # one-point probe: cmos5l / rewired / 3.3 V / mos_tt / 27 C
    req = request("ihp-sg13cmos5l", "../testbench/rerun329/tb_cmos5l_rewired_3p3.sp", "3.3", True)
    (REC / "requests/schmitt_rewire_probe.request.json").write_text(json.dumps(req, indent=2) + "\n")

main()
