#!/usr/bin/env python3
"""sg13g2-pll :: sim/sg13cmos5l-loop-bandwidth-pm/testbench/gen_rerun320_requests.py
(issue #320, child of #214, Part of #199, item 9) -- RECORD-006 of this slug.

Supersede RECORD-003 (issue #83) and RECORD-004 (issue #79) with a same-bench
rerun of their historical DUT through `klt sim`. The DUT is the frozen
`../netlist-snapshots/loop_filter_resized.spice` (unchanged since its only
commit, ffec56a, which predates both originals) driven by the unmodified
`tb_loop_ac_real_resized.sp.tmpl` scenario: an ideal Gcp (Kd = Icp/2pi), an
ideal VCO integrator (Kv = 2 pi Kvco) and a 1/N divider around the real
rppd/cap_cmomi loop filter. Kd/Kv/N are read from the originals' own committed
CSVs, exactly as run_issue83_finetrim.sh / run_issue79_finetrim.sh read them:

    PDK_ROOT=<parent of ihp-sg13cmos5l> python3 gen_rerun320_requests.py

Four loops (the originals' four rows) share one deck:
    dr008_fast / dr008_typ / dr008_slow   band 00, low, f_ref 4.5 MHz, 11 uA
    dr007_slow                            band 00, mid, f_ref 4.5 MHz, 3.75 uA
Every corner evaluates every loop; only a loop's OWN bundle is its result
(summarize_rerun320.py reads exactly those).

    rerun320_probe.request.json   slow bundle, ONE corner, batch (probe first)
    rerun320_bundles.request.json fast + typ + slow, batch fleet only

Icp is NOT remeasured here: it is the originals' own cp-icp-trim input
(../../sg13cmos5l-cp-icp-trim/corners/results_issue{83,79}_finetrim.csv), whose
supersession is #231. models.pdk is omitted on purpose (klt's batch backend
refuses ihp-sg13cmos5l, 2AMLogic/klayout-tools#2727); the model library ships
through options.stage_model_inputs, as in the RECORD-005 requests.
"""
import csv
import json
import math
import os
import pathlib

pdk_root = os.environ.get("PDK_ROOT", "/home/ubuntu/share/pdk")
tech = f"{pdk_root}/ihp-sg13cmos5l/libs.tech/ngspice"
here = pathlib.Path(__file__).resolve().parent
slug = here.parent
sim = slug.parent

RES_LIB = f"{tech}/models/cornerRES.lib"
CAP_LIB = f"{tech}/models/cap_cmomi.lib"

# bundle -> (res corner, temp_c, mos corner as keyed in the cp-icp-trim CSVs)
BUNDLES = {
    "fast": ("res_bcs", -40, "mos_ff"),
    "typ": ("res_typ", 27, "mos_tt"),
    "slow": ("res_wcs", 125, "mos_ss"),
}


def load(path):
    with open(path) as f:
        return list(csv.DictReader(f))


def icp_of(rows, mos, temp, code):
    for r in rows:
        if (r["mos_corner"] == mos and r["temp_c"] == str(temp)
                and r["vdd_v"] == "3.3" and r["iref_a"] == code
                and r["state"] == "up" and r["icp_a"] != "NA"):
            return abs(float(r["icp_a"]))
    raise SystemExit(f"no Icp row for {code} at {mos}/{temp}")


icp83 = load(sim / "sg13cmos5l-cp-icp-trim/corners/results_issue83_finetrim.csv")
icp79 = load(sim / "sg13cmos5l-cp-icp-trim/corners/results_issue79_finetrim.csv")
r83 = {r["pvt_bundle"]: r for r in
       load(slug / "corners/results_resized_issue83_finetrim.csv")}
r79 = {r["pvt_bundle"]: r for r in
       load(slug / "corners/results_resized_issue79_finetrim.csv")}

# loop id -> (bundle, committed original row, code, cp-icp-trim rows)
LOOPS = {
    "dr008_fast": ("fast", r79["fast"], "11u", icp79),
    "dr008_typ": ("typ", r79["typ"], "11u", icp79),
    "dr008_slow": ("slow", r79["slow"], "11u", icp79),
    "dr007_slow": ("slow", r83["slow"], "3.75u", icp83),
}


def loop(tag, bundle, row, code, icp_rows):
    _, temp, mos = BUNDLES[bundle]
    icp = icp_of(icp_rows, mos, temp, code)
    kd = repr(icp / (2 * math.pi))
    kv = repr(2 * math.pi * float(row["kvco_hz_per_v"]))
    invn = repr(1.0 / int(row["n_div"]))
    return f"""* --- loop {tag}: {bundle} bundle, trim {code}, n_div {row['n_div']}
Gcp_{tag} 0 vc_{tag} pe 0 {kd}
XLF_{tag} vc_{tag} 0 loop_filter
Gvco_{tag} 0 vph_{tag} vc_{tag} 0 {kv}
Cint_{tag} vph_{tag} 0 1
Rleak_{tag} vph_{tag} 0 1e15
Ediv_{tag} fb_{tag} 0 vph_{tag} 0 {invn}
"""


body = f"""* sg13g2-pll :: sim/sg13cmos5l-loop-bandwidth-pm (issue #320, RECORD-006)
* GENERATED by gen_rerun320_requests.py -- do not edit by hand.
* Circuit body for `klt sim` (AC, dec 200 10 1e9 as RECORD-002..004). Each loop
* is tb_loop_ac_real_resized.sp.tmpl's scenario verbatim (ideal Gcp, ideal VCO
* integrator, memoryless 1/N, REAL resized loop filter), Kd/Kv/N from the
* committed RECORD-003/004 CSVs and Icp from their cp-icp-trim inputs.
.include {CAP_LIB}
.include ../netlist-snapshots/loop_filter_resized.spice
.option scale=1
.global sub!

Vsub sub! 0 dc 0
Vpe pe 0 dc 0 ac 1
"""
for tag, (b, row, code, rows) in LOOPS.items():
    body += loop(tag, b, row, code, rows)
(here / "tb_loop_ac_rerun320.sp").write_text(body)

meas = []
for tag in LOOPS:
    meas += [
        {"name": f"fc_hz_{tag}", "unit": "Hz",
         "spice": f".meas ac fc_hz_{tag} when vdb(fb_{tag})=0"},
        {"name": f"ph_rad_{tag}", "unit": "rad",
         "spice": f".meas ac ph_rad_{tag} find vp(fb_{tag}) when vdb(fb_{tag})=0"},
        {"name": f"pm_deg_{tag}", "unit": "deg",
         "spice": f".meas ac pm_deg_{tag} param='180+ph_rad_{tag}*57.29577951308232'"},
    ]

base = {
    "engine": "ngspice",
    "models": {"lib": RES_LIB},
    "options": {
        "osdi_preload": [f"{tech}/osdi/{n}.osdi" for n in
                         ("cap_cmomi", "cap_cmomf", "r3_cmc")],
        "stage_model_inputs": True,
        "ngspice_init": ["set numdgt=12", "set num_threads=1"],
        "timeout_s": 900,
    },
    "netlist": "tb_loop_ac_rerun320.sp",
    "analysis": {"kind": "ac", "args": "dec 200 10 1e9"},
    "measurements": meas,
    "backend": "batch",
    "batch": {"capacity_wait_s": 600},
}


def emit(name, bundles):
    r = json.loads(json.dumps(base))
    temps = sorted({BUNDLES[b][1] for b in bundles})
    r["corners"] = {
        "process": [{"name": b, "sections": [{"lib": RES_LIB, "section": BUNDLES[b][0]}]}
                    for b in bundles],
        "temperature_c": temps,
    }
    ex = [{"process": b, "temperature_c": t}
          for b in bundles for t in temps if t != BUNDLES[b][1]]
    if ex:
        r["exclude"] = ex
    (here / name).write_text(json.dumps(r, indent=2) + "\n")


emit("rerun320_probe.request.json", ["slow"])
emit("rerun320_bundles.request.json", ["fast", "typ", "slow"])
