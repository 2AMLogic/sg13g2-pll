#!/usr/bin/env python3
"""Generate the klt-sim decks/requests for the #231 fine-trim reruns.

Reruns RECORD-003 (issue #83: 3.75 uA, mos_ss/125C/3.3V) and RECORD-004
(issue #79: 11 uA, mos_ff/-40C, mos_tt/27C, mos_ss/125C, all 3.3V).
The DUT is the frozen ../netlist-snapshots/cp.spice, unchanged since both
originals.  The originals ran tb_cp_dc.sp.tmpl once per (corner, state) and
read icp at the sweep point nearest VDD/2 (= 1.65 V, an exact grid point of
the 0.15..3.15 V, 50 mV sweep).  Here the three switch states are three
independent DUT instances in one deck, each with its own four reference
current sources and its own Vout source, evaluated at Vout = 1.65 V (a
one-point DC sweep).  Writes decks next to this script and one request per
corner.
"""
import json, pathlib

HERE = pathlib.Path(__file__).resolve().parent
VDD = 3.3
STATES = [("up", VDD, 0.0), ("dn", 0.0, VDD), ("both", VDD, VDD)]

def deck(iref):
    out = [f"* sg13g2-pll :: #231 rerun deck, Iref={iref} (generated by gen_finetrim_rerun231.py)",
           "* Circuit body for `klt sim` (no .control/.end; klt owns those).",
           ".option scale=1", ".include ../netlist-snapshots/cp.spice",
           f"Vdd VDD 0 dc {VDD}"]
    for s, up, dn in STATES:
        out += [f"XCP_{s} up_{s} dn_{s} ibp_{s} icp_{s} ibn_{s} icn_{s} vout_{s} VDD 0 cp",
                f"Irefbp_{s} ibp_{s} 0 dc {iref}", f"Irefcp_{s} icp_{s} 0 dc {iref}",
                f"Irefbn_{s} 0 ibn_{s} dc {iref}", f"Irefcn_{s} 0 icn_{s} dc {iref}",
                f"Vup_{s} up_{s} 0 dc {up}", f"Vdn_{s} dn_{s} 0 dc {dn}",
                f"Vout_{s} vout_{s} 0 dc 1.65"]
    return "\n".join(out) + "\n"

def request(netlist, proc, temp):
    return {
        "engine": "ngspice", "backend": "batch", "netlist": netlist,
        "models": {"pdk": "ihp-sg13cmos5l", "lib": "libs.tech/ngspice/models/cornerMOShv.lib"},
        "corners": {"process": [proc], "temperature_c": [temp]},
        "analysis": {"kind": "dc", "args": "Vout_up 1.65 1.65 0.05"},
        "measurements": [
            {"name": f"icp_{s}_a", "unit": "A", "expr": f"i(Vout_{s})"} for s, _, _ in STATES],
        "options": {
            "osdi_preload": [f"$PDK_ROOT/ihp-sg13cmos5l/libs.tech/ngspice/osdi/{o}.osdi"
                             for o in ("psp103", "psp103_nqs", "mosvar")],
            "ngspice_init": ["set numdgt=12", "set num_threads=1"],
            "timeout_s": 600, "keep_artifacts": True},
        "batch": {"capacity_wait_s": 600},
    }

# (tag, deck, iref, [(mos, temp)])
for dk, iref in (("3p75u", "3.75u"), ("11u", "11u")):
    (HERE / f"tb_cp_finetrim_{dk}.sp").write_text(deck(iref))
JOBS = {"issue83": ("tb_cp_finetrim_3p75u.sp", [("mos_ss", 125)]),
        "issue79": ("tb_cp_finetrim_11u.sp", [("mos_ff", -40), ("mos_tt", 27), ("mos_ss", 125)])}
for tag, (nl, pts) in JOBS.items():
    for m, t in pts:
        (HERE / f"finetrim_{tag}_{m}_{t}.rerun231.request.json").write_text(
            json.dumps(request(nl, m, t), indent=2) + "\n")
