#!/usr/bin/env python3
"""sg13g2-pll :: sim/sg13cmos5l-cp-icp-trim/testbench/gen_rerun_requests.py
(issue #230, Part of #212 / #199) -- reruns of RECORD-001 and RECORD-002.

Regenerates, for each original record, the `klt sim` circuit body and the
batch request files that re-measure the HISTORICAL cp (not today's DR-010 cp):

  rerun1  RECORD-001: ../netlist-snapshots/cp-b37918d.spice (the snapshot as
          committed in b37918d, pre-DR-006 cp) driven through a testbench-local
          diode-connected cascode mirror replica (XMREF*), as b37918d's
          tb_cp_dc.sp.tmpl did.
  rerun2  RECORD-002: ../netlist-snapshots/cp-f54b9ef.spice (DR-006 cp, on-chip
          cascode bias replica) driven by four ideal reference currents, as
          f54b9ef's tb_cp_dc.sp.tmpl did.

Original grid: 17 PVT points x 6 trim codes x 3 UP/DN states = 306 DC sweeps of
VOUT, 0.15 V -> VDD-0.15 V in 50 mV steps. Here ONE deck carries the 18
(trim code x state) instances for a PVT point (each with its own bias, switch
levels and 0 V ammeter Vm_<inst>, i > 0 = cp sources into the output, the same
sign as the original's i(Vout)); `klt sim` expands the corner axes. The sweep
range depends on VDD, so each record has three requests:

  <rerun>_pvt33   5 MOS corners x {-40, 27, 125} C at 3.3 V      (15 corners)
  <rerun>_v30     mos_tt / 27 C at 3.0 V                          (1 corner)
  <rerun>_v36     mos_tt / 27 C at 3.6 V                          (1 corner)

`results.csv` rows are the sweep point at VDD/2 (an exact grid point for every
supply); `compliance.csv` rows are the whole sweep at the 10 uA code. Both are
exposed as scalar `klt sim` measurements and folded back into CSV by
collect_rerun.py.

models.pdk is omitted on purpose and options.stage_model_inputs ships the
model library with the job, as in RECORD-005's requests.

    PDK_ROOT=<parent of ihp-sg13cmos5l> python3 gen_rerun_requests.py
"""
import json
import os
import pathlib

pdk_root = os.environ.get("PDK_ROOT", "/home/ubuntu/share/pdk")
tech = f"{pdk_root}/ihp-sg13cmos5l/libs.tech/ngspice"
here = pathlib.Path(__file__).resolve().parent

CODES = [("2p5", "2.5u"), ("5", "5u"), ("10", "10u"), ("20", "20u"), ("40", "40u"), ("80", "80u")]
STATES = [("up", 1, 0), ("dn", 0, 1), ("both", 1, 1)]
V0, VSTEP = 0.15, 0.05
SUPPLIES = {"pvt33": 3.3, "v30": 3.0, "v36": 3.6}
RERUNS = {
    "rerun1": dict(record="RECORD-001", snap="cp-b37918d.spice", bias="replica"),
    "rerun2": dict(record="RECORD-002", snap="cp-f54b9ef.spice", bias="onchip"),
}


def npts(vdd):
    return round(((vdd - 0.15) - V0) / VSTEP) + 1


def instance(rr, tag, iref, st, up, dn):
    n = f"{st}{tag}"
    L = [f"* --- {n}: UP={up} DN={dn} Iref={iref}"]
    if rr["bias"] == "replica":
        # b37918d: testbench-local diode-connected cascode mirror replicas,
        # W/L of the leg each mirrors; cp's IBP=ICP and IBN=ICN tied together.
        L += [
            f"XMREFP1_{n} nrp1_{n} nbp_{n} VDD VDD sg13_hv_pmos w=24u l=1u ng=1 m=1",
            f"XMREFP2_{n} nbp_{n} nbp_{n} nrp1_{n} VDD sg13_hv_pmos w=24u l=1u ng=1 m=1",
            f"Irefp_{n} nbp_{n} 0 dc {iref}",
            f"XMREFN1_{n} nrn1_{n} nbn_{n} 0 0 sg13_hv_nmos w=8u l=1u ng=1 m=1",
            f"XMREFN2_{n} nbn_{n} nbn_{n} nrn1_{n} 0 sg13_hv_nmos w=8u l=1u ng=1 m=1",
            f"Irefn_{n} 0 nbn_{n} dc {iref}",
            f"X{n} up_{n} dn_{n} nbp_{n} nbp_{n} nbn_{n} nbn_{n} vo_{n} VDD 0 cp",
        ]
    else:
        # f54b9ef: four ideal reference currents into cp's own bias replica.
        L += [
            f"X{n} up_{n} dn_{n} ibp_{n} icp_{n} ibn_{n} icn_{n} vo_{n} VDD 0 cp",
            f"Irbp_{n} ibp_{n} 0 dc {iref}",
            f"Ircp_{n} icp_{n} 0 dc {iref}",
            f"Irbn_{n} 0 ibn_{n} dc {iref}",
            f"Ircn_{n} 0 icn_{n} dc {iref}",
        ]
    L += [
        f"Bup_{n} up_{n} 0 V={'v(VDD)' if up else '0'}",
        f"Bdn_{n} dn_{n} 0 V={'v(VDD)' if dn else '0'}",
        # n+ on the cp side: i(Vm_<n>) > 0 means the cp SOURCES into the output.
        f"Vm_{n} vo_{n} vs dc 0",
    ]
    return "\n".join(L)


def body(rr, key, vdd):
    head = f"""* sg13g2-pll :: sim/sg13cmos5l-cp-icp-trim (issue #230, rerun of {rr['record']})
* GENERATED by gen_rerun_requests.py -- do not edit by hand.
* Circuit body for `klt sim` (no .control/.end; klt owns those).
* DUT: ../netlist-snapshots/{rr['snap']} (historical cp, NOT today's cp).
* 18 instances (6 trim codes x states up/dn/both) share ONE swept output
* voltage VS ({V0:.2f} -> {vdd - 0.15:.2f} V, 50 mV, {npts(vdd)} points; index k <-> {V0:.2f} + 0.05 k V).
* Each instance has its own 0 V ammeter Vm_<inst> (i > 0 = cp sources INTO the
* output). Switch levels follow VDD through B-sources.
.option scale=1
.include ../netlist-snapshots/{rr['snap']}

Vdd VDD 0 dc {vdd}
Vs vs 0 dc {vdd / 2:.4f}
"""
    parts = [head]
    for tag, iref in CODES:
        for st, up, dn in STATES:
            parts.append(instance(rr, tag, iref, st, up, dn))
    return "\n".join(parts) + "\n"


def measurements(vdd):
    mid = round((vdd / 2 - V0) / VSTEP)
    assert abs(V0 + mid * VSTEP - vdd / 2) < 1e-9
    m = [{"name": "vs_mid_v", "unit": "V", "expr": f"v(vs)[{mid}]"}]
    for tag, _ in CODES:
        for st, _, _ in STATES:
            m.append({"name": f"icp_mid_{st}_{tag}", "unit": "A",
                      "expr": f"i(Vm_{st}{tag})[{mid}]"})
    for st, _, _ in STATES:
        for k in range(npts(vdd)):
            m.append({"name": f"cmp_{st}_10_k{k:02d}", "unit": "A",
                      "expr": f"i(Vm_{st}10)[{k}]"})
    return m


def request(rr, key, vdd, deck):
    corners = {"process": ["mos_tt", "mos_ss", "mos_ff", "mos_sf", "mos_fs"],
               "temperature_c": [-40, 27, 125]} if key == "pvt33" else \
              {"process": ["mos_tt"], "temperature_c": [27]}
    return {
        "engine": "ngspice",
        "netlist": deck,
        "models": {"lib": f"{tech}/models/cornerMOShv.lib"},
        "analysis": {"kind": "dc", "args": f"Vs {V0:.2f} {vdd - 0.15:.2f} {VSTEP:.2f}"},
        "measurements": measurements(vdd),
        "options": {
            "osdi_preload": [f"{tech}/osdi/psp103.osdi", f"{tech}/osdi/psp103_nqs.osdi",
                             f"{tech}/osdi/mosvar.osdi"],
            "stage_model_inputs": True,
            "ngspice_init": ["set numdgt=12", "set num_threads=1"],
            "timeout_s": 900,
        },
        "backend": "batch",
        "batch": {"capacity_wait_s": 600},
        "corners": corners,
    }


for name, rr in RERUNS.items():
    for key, vdd in SUPPLIES.items():
        deck = f"tb_cp_{name}_{key}.sp"
        (here / deck).write_text(body(rr, key, vdd))
        (here / f"{name}_{key}.request.json").write_text(
            json.dumps(request(rr, key, vdd, deck), indent=2) + "\n")
        print("wrote", deck, f"{name}_{key}.request.json")
