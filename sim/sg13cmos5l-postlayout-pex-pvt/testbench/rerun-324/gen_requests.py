#!/usr/bin/env python3
"""sg13g2-pll :: sim/sg13cmos5l-postlayout-pex-pvt/testbench/rerun-324/gen_requests.py
(issue #324, Part of #215) -- regenerates inputs/, bodies/ and requests/ for the
RECORD-002 superseding rerun.

The original run.sh / run_rc_attribution.sh fan ngspice out with a shell loop.
On the dispatch host that is not allowed, so the same grids are `klt sim`
batch requests instead: one request per (variant, PVT bundle); the band code and
VCTRL point are a zipped `corners.params` axis (rows), the PVT bundle is
one process section + one temperature, and the coupled resistor corner is a
quoted `.lib "$PDK_ROOT/..."` card in the bundle's netlist body.

  python3 gen_requests.py     # needs ../../netlist-snapshots/rerun-324/pll_vco.pex.spice
"""
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
BENCH = os.path.abspath(os.path.join(HERE, "..", ".."))
TB = os.path.join(BENCH, "testbench")
SIM = os.path.dirname(BENCH)
PEX = os.path.join(BENCH, "netlist-snapshots", "rerun-324", "pll_vco.pex.spice")
SCH = os.path.join(SIM, "sg13cmos5l-vco-kvco-table", "netlist-snapshots", "vco.spice")

BUNDLES = [("typ", "mos_tt", "res_typ", 27),
           ("slow", "mos_ss", "res_wcs", 125),
           ("fast", "mos_ff", "res_bcs", -40)]
BANDS_ALL = [("00", 0.0, 0.0), ("10", 3.3, 0.0), ("01", 0.0, 3.3), ("11", 3.3, 3.3)]
BANDS_RC = [("00", 0.0, 0.0), ("11", 3.3, 3.3)]
VCTRL = [0.3, 0.9, 1.5, 2.1, 2.7]
RC_VARIANTS = [("full", False, False, 1.0), ("c_only", True, False, 1.0),
               ("r_only", False, True, 1.0), ("none", True, True, 1.0),
               ("cscale25", False, False, 0.25), ("cscale10", False, False, 0.10),
               ("cscale05", False, False, 0.05)]
OSDI = ["psp103", "psp103_nqs", "mosvar", "r3_cmc"]
PDK = "ihp-sg13cmos5l"

for d in ("inputs", "bodies", "requests"):
    os.makedirs(os.path.join(HERE, d), exist_ok=True)


def w(path, text):
    with open(os.path.join(HERE, path), "w") as f:
        f.write(text)


# --- inputs ---------------------------------------------------------------
full = os.path.join(HERE, "inputs", "vco_full.spice")
subprocess.run([sys.executable, os.path.join(TB, "pex-to-ngspice.py"), PEX, full], check=True)
inst = subprocess.run([sys.executable, os.path.join(TB, "make-inst.py"), full, "pll_vco", "vco",
                       "VCTRL=vctrl", "B0=b0", "B1=b1", "CLK=clk", "VDD_VCO=vdd", "GND_VCO=0"],
                      check=True, capture_output=True, text=True).stdout
w("inputs/vco_inst.spice", inst)
with open(SCH) as f:
    w("inputs/vco_open.spice", re.sub(r"(?m)^(XCDECAP)", r"*\1", f.read()))

par_r = re.compile(r"^(R\S+\s+\S+\s+\S+\s+)([-+0-9.eE]+)\s*$")
par_c = re.compile(r"^(C\S+\s+\S+\s+\S+\s+)([-+0-9.eE]+)\s*$")
par_c_any = re.compile(r"^C\S+\s+")
dev = re.compile(r"^[MXQD]", re.I)
src = open(full).read().splitlines()
base = None
for name, short_r, drop_c, c_scale in RC_VARIANTS:
    out, nr, nc, nd = [], 0, 0, 0
    for ln in src:
        if dev.match(ln):
            nd += 1
        m = par_r.match(ln)
        if m:
            nr += 1
            out.append(m.group(1) + ("1e-6" if short_r else m.group(2)))
            continue
        if par_c_any.match(ln):
            nc += 1
            if drop_c:
                out.append("*" + ln)
                continue
            if c_scale != 1.0:
                mc = par_c.match(ln)
                if not mc:
                    sys.exit("FATAL: unparseable parasitic C card: %r" % ln)
                out.append(mc.group(1) + repr(float(mc.group(2)) * c_scale))
                continue
        out.append(ln)
    counts = (nr, nc, nd)
    if base is None:
        base = counts
    elif counts != base:
        sys.exit("FATAL: variant %s changed card counts" % name)
    if name != "full":
        w("inputs/vco_%s.spice" % name, "\n".join(out) + "\n")

# --- bodies + requests ------------------------------------------------------
SRC_PEX = """Vvctrl vctrl 0 dc {p_vctrl}
Vb0 b0 0 dc {p_b0v}
Vb1 b1 0 dc {p_b1v}
Vdd vdd 0 dc 3.3
Vsub sub! 0 dc 0
Vsubs vsubs 0 dc 0
.ic v(ring1)=0.5
"""
SRC_SCH = """Vvctrl vctrl 0 dc {p_vctrl}
Vb0 b0 0 dc {p_b0v}
Vb1 b1 0 dc {p_b1v}
Vdd vdd 0 dc 3.3
Vsub sub! 0 dc 0
Xvco vctrl b0 b1 clk vdd 0 vco
.ic v(xvco.ring1)=0.5
"""


def emit(variant, arm, bands):
    for bname, mos, res, temp in BUNDLES:
        tag = "%s_%s" % (variant, bname)
        if arm == "postlayout":
            incs = ".include ../inputs/vco_%s.spice\n.include ../inputs/vco_inst.spice\n" % (
                "full" if variant == "postlayout" else variant)
            srcs = SRC_PEX
        else:
            incs = ".include ../inputs/vco_open.spice\n"
            srcs = SRC_SCH
        rows = [(b, b0, b1, v) for (b, b0, b1) in bands for v in VCTRL]
        body = ("* generated by gen_requests.py (issue #324); variant=%s bundle=%s\n"
                "* res corner %s comes from corners.process[].sections[] (cornerRES.lib)\n"
                ".option scale=1\n.global sub!\n%s"
                ".param p_vctrl=0.3 p_b0v=0 p_b1v=0\n%s") % (variant, bname, res, incs, srcs)
        w("bodies/%s.sp" % tag, body)
        req = {
            "engine": "ngspice",
            "backend": "batch",
            "netlist": "../bodies/%s.sp" % tag,
            "models": {"pdk": PDK, "lib": "libs.tech/ngspice/models/cornerMOShv.lib"},
            "corners": {
                "process": [{"name": "%s+%s" % (mos, res),
                             "sections": [mos, {"lib": "libs.tech/ngspice/models/cornerRES.lib",
                                                "section": res}]}],
                "temperature_c": [temp],
                "params": {"p_vctrl": [r[3] for r in rows],
                           "p_b0v": [r[1] for r in rows],
                           "p_b1v": [r[2] for r in rows]},
            },
            "analysis": {"kind": "tran", "args": "20p 30n"},
            "measurements": [{"name": "per1",
                              "spice": ".meas tran per1 trig v(clk) val=1.65 rise=3 targ v(clk) val=1.65 rise=4"}],
            "options": {
                "osdi_preload": ["$PDK_ROOT/%s/libs.tech/ngspice/osdi/%s.osdi" % (PDK, o) for o in OSDI],
                "timeout_s": 600,
                "keep_artifacts": True,
                "stage_model_inputs": True,
            },
            "batch": {"capacity_wait_s": 600},
        }
        w("requests/%s.request.json" % tag, json.dumps(req, indent=2) + "\n")


emit("postlayout", "postlayout", BANDS_ALL)
emit("schematic", "schematic", BANDS_ALL)
for name, *_ in RC_VARIANTS:
    if name != "full":
        emit(name, "postlayout", BANDS_RC)
# the RC-attribution "full" variant is the same netlist as the postlayout arm
# but over the 2-band subset; keep it as its own request.
emit_full = [("full", "postlayout", BANDS_RC)]
for v, a, b in emit_full:
    emit(v, a, b)
print("ok")
